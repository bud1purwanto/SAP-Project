// Read-only: bandingkan logic karakteristik/LQUA lama (per baris) vs bulk WMS. Usage: node compare_wms_bulk.mjs <server> [rows]
import { serverManager } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/server-manager.js';
import { HANDLERS } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/tool-registry.js';
const [server, rows = '2000'] = process.argv.slice(2);
const src = `REPORT ZTMP_WMSCMP LINE-SIZE 255.
TYPES: BEGIN OF TY_C, MATNR TYPE MATNR, CHARG TYPE CHARG_D,
 ATINN TYPE ATINN, ATWRT TYPE ATWRT, ATFLV TYPE ATFLV,
 ATWTB TYPE ATWTB, END OF TY_C.
TYPES: BEGIN OF TY_B, MATNR TYPE MATNR, WERKS TYPE WERKS_D,
 CHARG TYPE CHARG_D, LGPLA TYPE LGPLA, END OF TY_B.
TYPES: BEGIN OF TY_K, MATNR TYPE MATNR, CHARG TYPE CHARG_D,
 END OF TY_K.
TYPES: BEGIN OF TY_M, MATNR TYPE MATNR, CHARG TYPE CHARG_D,
 CUOBJ_BM TYPE CUOBJ_BM, END OF TY_M.
TYPES: BEGIN OF TY_O, MATNR TYPE MATNR, CHARG TYPE CHARG_D,
 OBJEK TYPE OBJNUM, END OF TY_O.
TYPES: BEGIN OF TY_J, OBJEK TYPE OBJNUM, END OF TY_J.
TYPES: BEGIN OF TY_A, OBJEK TYPE OBJNUM, ATINN TYPE ATINN,
 ATWRT TYPE ATWRT, ATFLV TYPE ATFLV, END OF TY_A.
DATA: LT_ROW TYPE TABLE OF TY_B, LS_ROW TYPE TY_B,
 LT_OLD TYPE TABLE OF TY_C, LS_C TYPE TY_C,
 LT_NEW TYPE TABLE OF TY_C,
 LT_TMP TYPE TABLE OF TY_C,
 LT_BO TYPE TABLE OF TY_B, LT_BN TYPE TABLE OF TY_B,
 LS_B TYPE TY_B, LT_LQ TYPE TABLE OF TY_B,
 LT_K TYPE TABLE OF TY_K, LS_K TYPE TY_K,
 LT_M TYPE TABLE OF TY_M, LS_M TYPE TY_M,
 LT_O TYPE TABLE OF TY_O, LS_O TYPE TY_O,
 LT_J TYPE TABLE OF TY_J, LS_J TYPE TY_J,
 LT_A TYPE TABLE OF TY_A, LS_A TYPE TY_A,
 LT_D TYPE TABLE OF TY_C, LS_D TYPE TY_C,
 LV_SQL(250) TYPE C, LV_CNT TYPE I,
 LV_IX TYPE SY-TABIX, T0 TYPE I, T1 TYPE I, T2 TYPE I,
 LV_N1 TYPE I, LV_N2 TYPE I, LV_TXT(72) TYPE C,
 V1 TYPE ATINN, V2 TYPE ATINN, V3 TYPE ATINN, V4 TYPE ATINN,
 V5 TYPE ATINN, V6 TYPE ATINN, V7 TYPE ATINN, V8 TYPE ATINN,
 V9 TYPE ATINN, V10 TYPE ATINN.
SELECT SINGLE ATINN INTO V1 FROM CABN WHERE ATNAM = 'ZZTYPE'.
SELECT SINGLE ATINN INTO V2 FROM CABN WHERE ATNAM = 'ZZTHICKNESS'.
SELECT SINGLE ATINN INTO V3 FROM CABN WHERE ATNAM = 'ZZWIDTH'.
SELECT SINGLE ATINN INTO V4 FROM CABN WHERE ATNAM = 'ZZLENGTH'.
SELECT SINGLE ATINN INTO V5 FROM CABN WHERE ATNAM = 'ZZALIAS'.
SELECT SINGLE ATINN INTO V6 FROM CABN
 WHERE ATNAM = 'ZZTYBCOMBINATIONNO'.
SELECT SINGLE ATINN INTO V7 FROM CABN WHERE ATNAM = 'ZZCRITERIA'.
SELECT SINGLE ATINN INTO V8 FROM CABN WHERE ATNAM = 'ZZCORE'.
SELECT SINGLE ATINN INTO V9 FROM CABN WHERE ATNAM = 'ZZCORETYPE'.
SELECT SINGLE ATINN INTO V10 FROM CABN WHERE ATNAM = 'ZZTREATMENT'.
SELECT MCHB~MATNR MCHB~WERKS MCHB~CHARG INTO TABLE LT_ROW
 FROM MCHB JOIN MCH1 ON MCH1~MATNR = MCHB~MATNR
 AND MCH1~CHARG = MCHB~CHARG
 JOIN AUSP ON AUSP~OBJEK = MCH1~CUOBJ_BM
 UP TO ${rows} ROWS
 WHERE AUSP~ATINN = V7 AND AUSP~KLART = '023'.
SELECT MATNR WERKS CHARG APPENDING TABLE LT_ROW FROM LQUA
 UP TO 500 ROWS WHERE CHARG <> SPACE.
GET RUN TIME FIELD T0.
LOOP AT LT_ROW INTO LS_ROW.
 REFRESH LT_TMP.
 SELECT AUSP~ATINN AUSP~ATWRT AUSP~ATFLV
  INTO CORRESPONDING FIELDS OF TABLE LT_TMP
  FROM AUSP JOIN MCH1 ON AUSP~OBJEK = MCH1~CUOBJ_BM
  WHERE MCH1~MATNR = LS_ROW-MATNR AND MCH1~CHARG = LS_ROW-CHARG
  AND AUSP~ATINN IN (V1, V2, V3, V4, V5, V6)
  AND AUSP~KLART = '023'.
 SELECT AUSP~ATINN AUSP~ATWRT AUSP~ATFLV CAWNT~ATWTB
  APPENDING CORRESPONDING FIELDS OF TABLE LT_TMP
  FROM MCH1 JOIN AUSP ON AUSP~OBJEK = MCH1~CUOBJ_BM
  JOIN CAWN ON AUSP~ATINN = CAWN~ATINN AND AUSP~ATWRT = CAWN~ATWRT
  JOIN CAWNT ON CAWN~ATINN = CAWNT~ATINN AND CAWN~ATZHL = CAWNT~ATZHL
  WHERE MCH1~MATNR = LS_ROW-MATNR AND MCH1~CHARG = LS_ROW-CHARG
  AND CAWNT~SPRAS = 'E'
  AND AUSP~ATINN IN (V7, V8, V9, V10) AND AUSP~KLART = '023'.
 LOOP AT LT_TMP INTO LS_C.
  LS_C-MATNR = LS_ROW-MATNR. LS_C-CHARG = LS_ROW-CHARG.
  APPEND LS_C TO LT_OLD.
 ENDLOOP.
 CLEAR LS_B. MOVE-CORRESPONDING LS_ROW TO LS_B. CLEAR LS_B-LGPLA.
 SELECT SINGLE LGPLA INTO LS_B-LGPLA FROM LQUA
  WHERE MATNR = LS_ROW-MATNR AND WERKS = LS_ROW-WERKS
  AND CHARG = LS_ROW-CHARG.
 APPEND LS_B TO LT_BO.
ENDLOOP.
GET RUN TIME FIELD T1.
SELECT CAWNT~ATINN CAWN~ATWRT CAWNT~ATWTB
 INTO CORRESPONDING FIELDS OF TABLE LT_D
 FROM CAWN JOIN CAWNT ON CAWN~ATINN EQ CAWNT~ATINN
 AND CAWN~ATZHL EQ CAWNT~ATZHL
 WHERE CAWN~ATINN IN (V7, V8, V9, V10) AND CAWNT~SPRAS EQ 'E'.
SORT LT_D BY ATINN ATWRT.
LOOP AT LT_ROW INTO LS_ROW.
 LS_K-MATNR = LS_ROW-MATNR. LS_K-CHARG = LS_ROW-CHARG.
 APPEND LS_K TO LT_K.
ENDLOOP.
SORT LT_K BY MATNR CHARG.
DELETE ADJACENT DUPLICATES FROM LT_K COMPARING MATNR CHARG.
IF LT_K IS NOT INITIAL.
 SELECT MATNR CHARG CUOBJ_BM INTO TABLE LT_M FROM MCH1
  FOR ALL ENTRIES IN LT_K
  WHERE MATNR = LT_K-MATNR AND CHARG = LT_K-CHARG
  %_HINTS ORACLE 'INDEX("MCH1" "MCH1~0")'
  ORACLE '&max_blocking_factor 100&'.
ENDIF.
LOOP AT LT_M INTO LS_M.
 LS_O-MATNR = LS_M-MATNR. LS_O-CHARG = LS_M-CHARG.
 LS_O-OBJEK = LS_M-CUOBJ_BM. APPEND LS_O TO LT_O.
 LS_J-OBJEK = LS_M-CUOBJ_BM. APPEND LS_J TO LT_J.
ENDLOOP.
SORT LT_O BY MATNR CHARG.
SORT LT_J BY OBJEK.
DELETE ADJACENT DUPLICATES FROM LT_J COMPARING OBJEK.
IF LT_J IS NOT INITIAL.
 SELECT OBJEK ATINN ATWRT ATFLV INTO TABLE LT_A FROM AUSP
  FOR ALL ENTRIES IN LT_J
  WHERE OBJEK = LT_J-OBJEK
  AND ATINN IN (V1, V2, V3, V4, V5, V6, V7, V8, V9, V10)
  AND KLART = '023'
  %_HINTS ORACLE 'INDEX("AUSP" "AUSP~N3")' ORACLE
'&max_in_blocking_factor 100&&max_blocking_factor 100&'.
ENDIF.
SORT LT_A BY OBJEK ATINN ATWRT.
IF LT_ROW IS NOT INITIAL.
 SELECT MATNR WERKS CHARG LGPLA INTO TABLE LT_LQ FROM LQUA
  FOR ALL ENTRIES IN LT_ROW
  WHERE MATNR = LT_ROW-MATNR AND WERKS = LT_ROW-WERKS
  AND CHARG = LT_ROW-CHARG
  %_HINTS ORACLE 'INDEX("LQUA" "LQUA~Z01")'
  ORACLE '&max_blocking_factor 100&'.
ENDIF.
SORT LT_LQ BY MATNR WERKS CHARG.
LOOP AT LT_ROW INTO LS_ROW.
 READ TABLE LT_O INTO LS_O WITH KEY MATNR = LS_ROW-MATNR
  CHARG = LS_ROW-CHARG BINARY SEARCH.
 IF SY-SUBRC = 0.
  READ TABLE LT_A TRANSPORTING NO FIELDS
   WITH KEY OBJEK = LS_O-OBJEK BINARY SEARCH.
  IF SY-SUBRC = 0.
   LV_IX = SY-TABIX.
   LOOP AT LT_A INTO LS_A FROM LV_IX.
    IF LS_A-OBJEK <> LS_O-OBJEK. EXIT. ENDIF.
    CLEAR LS_C.
    LS_C-MATNR = LS_ROW-MATNR. LS_C-CHARG = LS_ROW-CHARG.
    LS_C-ATINN = LS_A-ATINN. LS_C-ATWRT = LS_A-ATWRT.
    LS_C-ATFLV = LS_A-ATFLV.
    IF LS_C-ATINN = V7 OR LS_C-ATINN = V8 OR
       LS_C-ATINN = V9 OR LS_C-ATINN = V10.
     READ TABLE LT_D INTO LS_D WITH KEY ATINN = LS_C-ATINN
      ATWRT = LS_C-ATWRT BINARY SEARCH.
     IF SY-SUBRC <> 0. CONTINUE. ENDIF.
     LS_C-ATWTB = LS_D-ATWTB.
    ENDIF.
    APPEND LS_C TO LT_NEW.
   ENDLOOP.
  ENDIF.
 ENDIF.
 CLEAR LS_B. MOVE-CORRESPONDING LS_ROW TO LS_B. CLEAR LS_B-LGPLA.
 READ TABLE LT_LQ INTO LS_B WITH KEY MATNR = LS_ROW-MATNR
  WERKS = LS_ROW-WERKS CHARG = LS_ROW-CHARG BINARY SEARCH.
 IF SY-SUBRC <> 0.
  CLEAR LS_B. MOVE-CORRESPONDING LS_ROW TO LS_B.
 ENDIF.
 APPEND LS_B TO LT_BN.
ENDLOOP.
GET RUN TIME FIELD T2.
T1 = T1 - T0. T2 = T2 - T0 - T1.
LV_N1 = LINES( LT_ROW ).
WRITE: / 'ROWS', LV_N1.
WRITE: / 'OLD_US', T1, 'NEW_US', T2.
SORT LT_OLD BY MATNR CHARG ATINN ATWRT ATFLV ATWTB.
DELETE ADJACENT DUPLICATES FROM LT_OLD COMPARING ALL FIELDS.
SORT LT_NEW BY MATNR CHARG ATINN ATWRT ATFLV ATWTB.
DELETE ADJACENT DUPLICATES FROM LT_NEW COMPARING ALL FIELDS.
LV_N1 = LINES( LT_OLD ). LV_N2 = LINES( LT_NEW ).
WRITE: / 'CHAR_OLD', LV_N1, 'CHAR_NEW', LV_N2.
IF LT_OLD = LT_NEW. WRITE: / 'CHAR_EQUAL'.
ELSE. WRITE: / 'CHAR_DIFF'. ENDIF.
CLEAR: LV_N1, LV_N2.
LOOP AT LT_BO INTO LS_B.
 LV_IX = SY-TABIX.
 READ TABLE LT_BN INTO LS_ROW INDEX LV_IX.
 IF LS_ROW-LGPLA <> LS_B-LGPLA.
  IF LS_ROW-LGPLA IS INITIAL OR LS_B-LGPLA IS INITIAL.
   LV_N1 = LV_N1 + 1.
  ELSE.
   LV_N2 = LV_N2 + 1.
  ENDIF.
 ENDIF.
ENDLOOP.
WRITE: / 'BIN_BLANKDIFF', LV_N1, 'BIN_MULTIQUANT_DIFF', LV_N2.
LV_N1 = LINES( LT_LQ ).
WRITE: / 'LQUA_ROWS', LV_N1.
DEFINE M_VSQL.
 CLEAR: LV_SQL, LV_CNT.
 TRY.
 EXEC SQL.
  SELECT COUNT(*) INTO :LV_CNT FROM V$SQL WHERE SQL_TEXT LIKE &1
 ENDEXEC.
 EXEC SQL.
  SELECT SUBSTR(SQL_TEXT, 1, 250) INTO :LV_SQL FROM V$SQL
  WHERE SQL_TEXT LIKE &1 AND ROWNUM = 1
 ENDEXEC.
 CATCH CX_SY_NATIVE_SQL_ERROR.
  LV_SQL = 'NO ACCESS V$SQL'.
 ENDTRY.
 WRITE: / 'VSQL', &1, LV_CNT.
 WRITE: / LV_SQL.
END-OF-DEFINITION.
M_VSQL '%AUSP~N3%'.
M_VSQL '%MCH1~0%'.
M_VSQL '%LQUA~Z01%'.
`;
const lines = src.split('\n').filter(l => l.trim());
