import { serverManager } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/server-manager.js';
import { call_function } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/tools/query-tools.js';
const prog = `REPORT ZFLOWDOC.
DATA: LT_LIPS TYPE TABLE OF LIPS WITH HEADER LINE,
      LV_MAT TYPE MCH1-MATNR, LV_LIC TYPE MCH1-LICHA,
      LV_CU TYPE MCH1-CUOBJ_BM, LV_OBJ TYPE INOB-OBJEK,
      LV_LOT TYPE QALS-PRUEFLOS, LV_ART TYPE QALS-ART,
      LV_KUN TYPE LIKP-KUNAG, LV_LF TYPE LIKP-LFART.
DATA: BEGIN OF LT_V OCCURS 0, ATNAM TYPE CABN-ATNAM,
      ATWRT TYPE AUSP-ATWRT, ATFLV TYPE AUSP-ATFLV, END OF LT_V.
DATA: LT_M TYPE TABLE OF MSEG WITH HEADER LINE.
DATA: LT_Z TYPE TABLE OF ZMAP_COA WITH HEADER LINE.
DATA: R_V TYPE RANGE OF LIPS-VBELN WITH HEADER LINE.
DEFINE ADDV. R_V-SIGN = 'I'. R_V-OPTION = 'EQ'. R_V-LOW = &1.
 APPEND R_V. END-OF-DEFINITION.
ADDV '0085006276'. ADDV '0085006277'.
ADDV '0085006278'. ADDV '0085006279'.
SELECT * FROM LIPS INTO TABLE LT_LIPS WHERE VBELN IN R_V
  AND CHARG <> ''.
SORT LT_LIPS BY VBELN CHARG.
DELETE ADJACENT DUPLICATES FROM LT_LIPS COMPARING VBELN MATNR.
LOOP AT LT_LIPS.
 SELECT SINGLE KUNAG LFART INTO (LV_KUN, LV_LF) FROM LIKP
  WHERE VBELN = LT_LIPS-VBELN.
 WRITE: / 'DO', LT_LIPS-VBELN, LT_LIPS-MATNR, LT_LIPS-CHARG,
  LT_LIPS-WERKS, LV_KUN, LV_LF.
 SELECT SINGLE CUOBJ_BM LICHA INTO (LV_CU, LV_LIC) FROM MCH1
  WHERE MATNR = LT_LIPS-MATNR AND CHARG = LT_LIPS-CHARG.
 WRITE: / ' LICHA', LV_LIC.
 SELECT SINGLE OBJEK INTO LV_OBJ FROM INOB WHERE CUOBJ = LV_CU.
 REFRESH LT_V.
 SELECT C~ATNAM A~ATWRT A~ATFLV INTO TABLE LT_V
  FROM AUSP AS A INNER JOIN CABN AS C ON C~ATINN = A~ATINN
  WHERE A~OBJEK = LV_CU AND A~KLART = '023' AND C~ATNAM IN
  ('ZZALIAS','ZZCODE','ZZTYPE','ZZTHICKNESS').
 LOOP AT LT_V. WRITE: / ' CH', LT_V-ATNAM, LT_V-ATWRT,
  LT_V-ATFLV EXPONENT 0 DECIMALS 1. ENDLOOP.
 SELECT SINGLE PRUEFLOS ART INTO (LV_LOT, LV_ART) FROM QALS
  WHERE CHARG = LT_LIPS-CHARG.
 WRITE: / ' QALS', LV_LOT, LV_ART.
 REFRESH LT_M.
 SELECT * FROM MSEG INTO TABLE LT_M UP TO 5 ROWS
  WHERE CHARG = LT_LIPS-CHARG AND BWART IN ('101','309','311').
 LOOP AT LT_M. WRITE: / ' MSEG', LT_M-BWART, LT_M-AUFNR,
  LT_M-EBELN, LT_M-LIFNR, LT_M-MATNR. ENDLOOP.
 REFRESH LT_Z.
 SELECT * FROM ZMAP_COA INTO TABLE LT_Z
  WHERE MATNR = LT_LIPS-MATNR.
 LOOP AT LT_Z. WRITE: / ' MAP', LT_Z-MIC, LT_Z-KUNNR,
  LT_Z-MAPPING. ENDLOOP.
ENDLOOP.`.split('\n');
for (const l of prog) if (l.length > 72) throw new Error('long: '+l);
await serverManager.loadConfig();
await serverManager.setActiveServer('Development AIX');
const res = await call_function({ function_name: 'RFC_ABAP_INSTALL_AND_RUN',
  parameters: { PROGRAM: prog.map(l => ({ LINE: l })) } });
console.log(JSON.stringify(res.result?.ERRORMESSAGE||''));
for (const w of res.result?.WRITES||[]) console.log(w.ZEILE);
process.exit(0);
