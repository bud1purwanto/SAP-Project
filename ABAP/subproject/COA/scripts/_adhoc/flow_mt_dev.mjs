import { serverManager } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/server-manager.js';
import { call_function } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/tools/query-tools.js';
const prog = `REPORT ZFLOWMT.
DATA: LV_SR TYPE CHARG_D, LV_JR TYPE CHARG_D, LV_MAT TYPE MCH1-MATNR,
 LV_LIC TYPE MCH1-LICHA, LV_LOT TYPE QALS-PRUEFLOS, LV_A TYPE AUFNR,
 LV_C TYPE AUFNR, LV_T TYPE MKPF-BKTXT, LV_LEN TYPE I.
DATA: LT_M TYPE TABLE OF MSEG WITH HEADER LINE.
LV_SR = '0000406850'.
DO 6 TIMES.
 CLEAR: LV_MAT, LV_LOT, LV_JR, LV_LIC.
 SELECT SINGLE MATNR INTO LV_MAT FROM MCH1 WHERE CHARG = LV_SR.
 SELECT SINGLE PRUEFLOS INTO LV_LOT FROM QALS WHERE CHARG = LV_SR
  AND ART = 'Z04'.
 WRITE: / 'SR', LV_SR, LV_MAT(8), 'LOT', LV_LOT.
 CALL FUNCTION 'ZQM_GET_BATCH_JR_BY_SR'
  EXPORTING CHARG_S = LV_SR IMPORTING CHARG_J = LV_JR.
 IF LV_JR IS INITIAL. WRITE: / ' no JR'. EXIT. ENDIF.
 CLEAR: LV_MAT, LV_LOT, LV_A, LV_C, LV_T.
 SELECT SINGLE MATNR INTO LV_MAT FROM MCH1 WHERE CHARG = LV_JR.
 SELECT SINGLE PRUEFLOS INTO LV_LOT FROM QALS WHERE CHARG = LV_JR
  AND ART IN ('Z02','Z03').
 WRITE: / 'JR', LV_JR, LV_MAT(8), 'LOT', LV_LOT.
 SELECT SINGLE AUFNR MBLNR MJAHR INTO (LV_A, LT_M-MBLNR, LT_M-MJAHR)
  FROM MSEG WHERE CHARG = LV_JR AND BWART = '101' AND SMBLN = ''.
 SELECT SINGLE BKTXT INTO LV_T FROM MKPF WHERE MBLNR = LT_M-MBLNR
  AND MJAHR = LT_M-MJAHR.
 SELECT SINGLE AUFNR INTO LV_C FROM AFPO WHERE MILL_OC_AUFNR_U = LV_A.
 IF SY-SUBRC = 0. LV_A = LV_C. ENDIF.
 WRITE: / ' order', LV_A, 'bktxt', LV_T(25).
 REFRESH LT_M.
 SELECT * FROM MSEG INTO TABLE LT_M WHERE AUFNR = LV_A
  AND BWART IN ('261','901') AND CHARG <> '' AND SMBLN = ''.
 CLEAR LV_SR.
 LOOP AT LT_M.
  SELECT SINGLE BKTXT INTO LV_C FROM MKPF WHERE MBLNR = LT_M-MBLNR
   AND MJAHR = LT_M-MJAHR.
  IF LV_C = LV_T(12) OR LV_T IS INITIAL. LV_SR = LT_M-CHARG.
   LV_MAT = LT_M-MATNR. EXIT. ENDIF.
 ENDLOOP.
 IF LV_SR IS INITIAL. READ TABLE LT_M INDEX 1.
  LV_SR = LT_M-CHARG. LV_MAT = LT_M-MATNR. ENDIF.
 IF LV_SR IS INITIAL. WRITE: / ' no component -> JR BASE'. EXIT. ENDIF.
 SELECT SINGLE LICHA INTO LV_LIC FROM MCH1 WHERE CHARG = LV_SR.
 WRITE: / ' comp', LV_SR, LV_MAT(8), 'LICHA', LV_LIC.
 LV_LEN = STRLEN( LV_MAT ) - 1.
 IF LV_MAT(2) = 'SR' AND LV_LIC IS NOT INITIAL AND
  ( LV_MAT+LV_LEN(1) = 'A' OR LV_MAT+LV_LEN(1) = 'O' ).
  LV_SR = LV_LIC. ENDIF.
ENDDO.`.split('\n');
for (const l of prog) if (l.length > 72) throw new Error('long: '+l);
await serverManager.loadConfig();
await serverManager.setActiveServer('Development AIX');
const res = await call_function({ function_name: 'RFC_ABAP_INSTALL_AND_RUN',
  parameters: { PROGRAM: prog.map(l => ({ LINE: l })) } });
console.log(JSON.stringify(res.result?.ERRORMESSAGE||''));
for (const w of res.result?.WRITES||[]) console.log(w.ZEILE);
process.exit(0);
