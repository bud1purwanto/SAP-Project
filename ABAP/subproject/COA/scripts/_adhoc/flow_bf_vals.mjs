import { serverManager } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/server-manager.js';
import { call_function } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/tools/query-tools.js';
const prog = `REPORT ZFLOWOV.
DATA: LT_L TYPE TABLE OF LIPS WITH HEADER LINE, LV_J TYPE CHARG_D,
 LV_A TYPE AUFNR, LV_C TYPE AUFNR, LV_LOT TYPE QALS-PRUEFLOS.
DATA: LT_M TYPE TABLE OF MSEG WITH HEADER LINE.
DATA: BEGIN OF LT_LOT OCCURS 0, STG(6), CHARG TYPE CHARG_D,
 LOT TYPE QALS-PRUEFLOS, END OF LT_LOT.
DATA: LT_Z TYPE TABLE OF ZMAP_COA WITH HEADER LINE,
 LV_MK TYPE QAMV-MERKNR, LV_V TYPE QAMR-MITTELWERT.
SELECT * FROM LIPS INTO TABLE LT_L WHERE VBELN = '0085006276'
 AND CHARG <> ''.
LOOP AT LT_L.
 CLEAR LV_LOT. SELECT SINGLE PRUEFLOS INTO LV_LOT FROM QALS
  WHERE CHARG = LT_L-CHARG AND ART = 'Z04'.
 LT_LOT-STG = 'SRCONV'. LT_LOT-CHARG = LT_L-CHARG.
 LT_LOT-LOT = LV_LOT. APPEND LT_LOT.
 CLEAR LV_J. CALL FUNCTION 'ZQM_GET_BATCH_JR_BY_SR'
  EXPORTING CHARG_S = LT_L-CHARG IMPORTING CHARG_J = LV_J.
 CLEAR LV_LOT. SELECT SINGLE PRUEFLOS INTO LV_LOT FROM QALS
  WHERE CHARG = LV_J AND ART IN ('Z02','Z03').
 LT_LOT-STG = 'JRCONV'. LT_LOT-CHARG = LV_J. LT_LOT-LOT = LV_LOT.
 APPEND LT_LOT.
 CLEAR: LV_A, LV_C.
 SELECT SINGLE AUFNR INTO LV_A FROM MSEG WHERE CHARG = LV_J
  AND BWART = '101' AND SMBLN = ''.
 SELECT SINGLE AUFNR INTO LV_C FROM AFPO WHERE MILL_OC_AUFNR_U = LV_A.
 IF SY-SUBRC = 0. LV_A = LV_C. ENDIF.
 REFRESH LT_M.
 SELECT * FROM MSEG INTO TABLE LT_M WHERE AUFNR = LV_A
  AND BWART IN ('261','901') AND CHARG <> '' AND SMBLN = ''.
 LOOP AT LT_M.
  CLEAR LV_LOT. SELECT SINGLE PRUEFLOS INTO LV_LOT FROM QALS
   WHERE CHARG = LT_M-CHARG AND ART = 'Z04'.
  LT_LOT-STG = 'SRBASE'. LT_LOT-CHARG = LT_M-CHARG.
  LT_LOT-LOT = LV_LOT. APPEND LT_LOT.
 ENDLOOP.
ENDLOOP.
SORT LT_LOT BY STG CHARG. DELETE ADJACENT DUPLICATES FROM LT_LOT
 COMPARING STG CHARG.
LOOP AT LT_LOT. WRITE: / 'LOT', LT_LOT-STG, LT_LOT-CHARG, LT_LOT-LOT.
ENDLOOP.
SELECT * FROM ZMAP_COA INTO TABLE LT_Z WHERE MATNR = 'SRACBI'.
SORT LT_Z BY SEQ_NO.
LOOP AT LT_Z.
 WRITE: / 'MIC', LT_Z-SEQ_NO, LT_Z-MIC, LT_Z-KUNNR, LT_Z-MAPPING,
  LT_Z-MIC_DESC.
 LOOP AT LT_LOT WHERE LOT IS NOT INITIAL.
  CLEAR LV_MK. SELECT SINGLE MERKNR INTO LV_MK FROM QAMV
   WHERE PRUEFLOS = LT_LOT-LOT AND VERWMERKM = LT_Z-MIC.
  CHECK SY-SUBRC = 0.
  CLEAR LV_V. SELECT SINGLE MITTELWERT INTO LV_V FROM QAMR
   WHERE PRUEFLOS = LT_LOT-LOT AND MERKNR = LV_MK.
  WRITE: / '  V', LT_LOT-STG, LT_LOT-CHARG, LT_LOT-LOT,
   LV_V EXPONENT 0 DECIMALS 3.
 ENDLOOP.
ENDLOOP.`.split('\n');
for (const l of prog) if (l.length > 72) throw new Error('long: '+l);
await serverManager.loadConfig();
await serverManager.setActiveServer('Development AIX');
const res = await call_function({ function_name: 'RFC_ABAP_INSTALL_AND_RUN',
  parameters: { PROGRAM: prog.map(l => ({ LINE: l })) } });
console.log(JSON.stringify(res.result?.ERRORMESSAGE||''));
for (const w of res.result?.WRITES||[]) console.log(w.ZEILE.replace(/\s+/g,' '));
process.exit(0);
