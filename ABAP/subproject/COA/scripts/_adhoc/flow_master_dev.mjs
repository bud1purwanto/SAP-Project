import { serverManager } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/server-manager.js';
import { call_function } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/tools/query-tools.js';
const prog = `REPORT ZFLOWMD.
DATA: LT_F TYPE TABLE OF DD03L WITH HEADER LINE,
 LV_T TYPE DD04T-SCRTEXT_L,
 LV_N TYPE I, LV_TAB TYPE TABNAME.
DATA: LT_TAB TYPE TABLE OF TABNAME WITH HEADER LINE.
APPEND 'ZMAP_COA' TO LT_TAB. APPEND 'ZQM_COA_CUST_COL' TO LT_TAB.
APPEND 'ZMAP_TYPE' TO LT_TAB. APPEND 'ZLOG_COA' TO LT_TAB.
LOOP AT LT_TAB.
 SELECT COUNT(*) INTO LV_N FROM (LT_TAB).
 WRITE: / '###', LT_TAB, 'rows', LV_N.
 REFRESH LT_F.
 SELECT * FROM DD03L INTO TABLE LT_F WHERE TABNAME = LT_TAB
  AND AS4LOCAL = 'A'.
 SORT LT_F BY POSITION.
 LOOP AT LT_F WHERE FIELDNAME(1) <> '.'.
  CLEAR LV_T.
  SELECT SINGLE SCRTEXT_L INTO LV_T FROM DD04T
   WHERE ROLLNAME = LT_F-ROLLNAME AND DDLANGUAGE = 'E'.
  IF LV_T IS INITIAL.
   SELECT SINGLE DDTEXT INTO LV_T FROM DD03T WHERE TABNAME = LT_TAB
    AND FIELDNAME = LT_F-FIELDNAME AND DDLANGUAGE = 'E'.
  ENDIF.
  WRITE: / LT_F-FIELDNAME(16), LT_F-KEYFLAG, LT_F-DATATYPE,
   LT_F-LENG, LV_T(30).
 ENDLOOP.
ENDLOOP.
DATA: LT_Z TYPE TABLE OF ZMAP_COA WITH HEADER LINE.
SELECT * FROM ZMAP_COA INTO TABLE LT_Z WHERE MATNR = 'SRGLBI'.
LOOP AT LT_Z. WRITE: / 'Z', LT_Z-MATNR, LT_Z-KUNNR, LT_Z-MIC,
 LT_Z-METHOD, LT_Z-MAPPING, LT_Z-UOM, LT_Z-MIC_DESC,
 LT_Z-LOWER_LIMIT, LT_Z-UPPER_LIMIT, LT_Z-SEQ_NO. ENDLOOP.
DATA: LT_C TYPE TABLE OF ZQM_COA_CUST_COL WITH HEADER LINE.
SELECT * FROM ZQM_COA_CUST_COL INTO TABLE LT_C UP TO 12 ROWS.
LOOP AT LT_C. WRITE: / 'C', LT_C-KUNNR, LT_C-FIELD_NAME,
 LT_C-FIELD_LABEL, LT_C-SEQ_NO, LT_C-COL_SIZE, LT_C-ACTIVE. ENDLOOP.
DATA: LT_Y TYPE TABLE OF ZMAP_TYPE WITH HEADER LINE.
SELECT * FROM ZMAP_TYPE INTO TABLE LT_Y WHERE PROG LIKE 'ZQM%'.
LOOP AT LT_Y. WRITE: / 'Y', LT_Y-PROG, LT_Y-TYPE,
 LT_Y-VALUE.
ENDLOOP.
DATA: LT_Q TYPE TABLE OF QPMK WITH HEADER LINE, LV_K TYPE QPMT-KURZTEXT.
SELECT * FROM QPMK INTO TABLE LT_Q WHERE MKMNR IN
 ('PGLASHMD','SGLASTCD','PAH8TSMD','PGLBOD00').
LOOP AT LT_Q. CLEAR LV_K. SELECT SINGLE KURZTEXT INTO LV_K FROM QPMT
 WHERE MKMNR = LT_Q-MKMNR AND SPRACHE = 'E'.
 WRITE: / 'Q', LT_Q-ZAEHLER, LT_Q-MKMNR, LT_Q-VERSION, LT_Q-STELLEN,
  LT_Q-MASSEINHSW, LT_Q-TOLERANZUN EXPONENT 0 DECIMALS 2,
  LT_Q-TOLERANZOB EXPONENT 0 DECIMALS 2, LV_K(30). ENDLOOP.`.split('\n');
for (const l of prog) if (l.length > 72) throw new Error('long: '+l);
await serverManager.loadConfig();
await serverManager.setActiveServer('Development AIX');
const res = await call_function({ function_name: 'RFC_ABAP_INSTALL_AND_RUN',
  parameters: { PROGRAM: prog.map(l => ({ LINE: l })) } });
console.log(JSON.stringify(res.result?.ERRORMESSAGE||''));
for (const w of res.result?.WRITES||[]) console.log(w.ZEILE);
process.exit(0);
