// Read-only: jalankan ZBAP_STOCK_BY_CHAR1 (Screen) via SUBMIT + CL_SALV_BS_RUNTIME_INFO, tangkap data ALV.
// Usage: node capture_alv.mjs <server> <out.json>
import { writeFileSync } from 'fs';
import { serverManager } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/server-manager.js';
import { HANDLERS } from 'file:///var/www/MCP/MCP%20SAP/sap-leader-mcp/src/tool-registry.js';
const [server, out] = process.argv.slice(2);
const src = `REPORT ZTMP_ALVCAP LINE-SIZE 255.
DATA: LR_DATA TYPE REF TO DATA,
 LS_META TYPE CL_SALV_BS_RUNTIME_INFO=>S_TYPE_METADATA,
 LT_FCAT TYPE LVC_T_FCAT, LS_FCAT TYPE LVC_S_FCAT,
 LV_ROW TYPE STRING, LV_VAL TYPE STRING, LV_LEN TYPE I,
 LV_OFF TYPE I, LV_PRE(1) TYPE C, LV_OUT(256) TYPE C,
 LV_N TYPE I, T0 TYPE I, T1 TYPE I, LV_TXT TYPE STRING.
DATA: R_MATNR TYPE RANGE OF MATNR, RS_MATNR LIKE LINE OF R_MATNR,
 R_WERKS TYPE RANGE OF WERKS_D, RS_WERKS LIKE LINE OF R_WERKS.
FIELD-SYMBOLS: <LT> TYPE STANDARD TABLE, <LS> TYPE ANY,
 <LF> TYPE ANY, <LM> TYPE ANY.
RS_MATNR-SIGN = 'I'. RS_MATNR-OPTION = 'CP'.
RS_MATNR-LOW = 'SR*'. APPEND RS_MATNR TO R_MATNR.
RS_WERKS-SIGN = 'I'. RS_WERKS-OPTION = 'CP'.
RS_WERKS-LOW = '*'. APPEND RS_WERKS TO R_WERKS.
CL_SALV_BS_RUNTIME_INFO=>SET( DISPLAY = ABAP_FALSE
 METADATA = ABAP_TRUE DATA = ABAP_TRUE ).
GET RUN TIME FIELD T0.
SUBMIT ZBAP_STOCK_BY_CHAR1 WITH S_MATNR IN R_MATNR
 WITH S_WERKS IN R_WERKS WITH P_ZERO = 'X'
 WITH LRB1 = 'X' AND RETURN.
GET RUN TIME FIELD T1.
T1 = ( T1 - T0 ) / 1000000.
LV_TXT = T1. CONCATENATE 'T|' LV_TXT INTO LV_OUT. WRITE: / LV_OUT.
TRY.
 CL_SALV_BS_RUNTIME_INFO=>GET_DATA_REF( IMPORTING R_DATA = LR_DATA ).
 LS_META = CL_SALV_BS_RUNTIME_INFO=>GET_METADATA( ).
 CATCH CX_SALV_BS_SC_RUNTIME_INFO.
 WRITE: / 'E|NO ALV DATA'.
 RETURN.
ENDTRY.
CL_SALV_BS_RUNTIME_INFO=>CLEAR_ALL( ).
ASSIGN COMPONENT 'T_FCAT' OF STRUCTURE LS_META TO <LM>.
IF SY-SUBRC = 0. LT_FCAT = <LM>. ENDIF.
SORT LT_FCAT BY COL_POS.
LOOP AT LT_FCAT INTO LS_FCAT.
 LV_TXT = LS_FCAT-COLTEXT.
 IF LV_TXT IS INITIAL. LV_TXT = LS_FCAT-SCRTEXT_L. ENDIF.
 IF LV_TXT IS INITIAL. LV_TXT = LS_FCAT-REPTEXT. ENDIF.
 CONCATENATE 'H|' LS_FCAT-FIELDNAME '|' LV_TXT '|' LS_FCAT-NO_OUT
  '|' LS_FCAT-TECH INTO LV_OUT.
 WRITE: / LV_OUT.
ENDLOOP.
ASSIGN LR_DATA->* TO <LT>.
LOOP AT <LT> ASSIGNING <LS>.
 CLEAR LV_ROW.
 LOOP AT LT_FCAT INTO LS_FCAT WHERE NO_OUT = SPACE
  AND TECH = SPACE.
  ASSIGN COMPONENT LS_FCAT-FIELDNAME OF STRUCTURE <LS> TO <LF>.
  IF SY-SUBRC = 0. LV_VAL = <LF>. ELSE. CLEAR LV_VAL. ENDIF.
  CONDENSE LV_VAL.
  REPLACE ALL OCCURRENCES OF '|' IN LV_VAL WITH '/'.
  CONCATENATE LV_ROW LV_VAL '|' INTO LV_ROW.
 ENDLOOP.
 LV_LEN = STRLEN( LV_ROW ). LV_OFF = 0. LV_PRE = 'R'.
 WHILE LV_OFF < LV_LEN.
  LV_N = LV_LEN - LV_OFF.
  IF LV_N > 250. LV_N = 250. ENDIF.
  CONCATENATE LV_PRE '|' LV_ROW+LV_OFF(LV_N) INTO LV_OUT
   RESPECTING BLANKS.
  WRITE: / LV_OUT.
  LV_OFF = LV_OFF + LV_N. LV_PRE = 'C'.
 ENDWHILE.
ENDLOOP.
LV_N = LINES( <LT> ). LV_TXT = LV_N.
CONCATENATE 'N|' LV_TXT INTO LV_OUT. WRITE: / LV_OUT.
`;
const lines = src.split('\n').filter(l => l.trim());
const bad = lines.filter(l => l.length > 72);
if (bad.length) { console.log('TOO LONG:', bad); process.exit(1); }
await serverManager.loadConfig();
await serverManager.setActiveServer(server);
const res = await HANDLERS.call_function({ function_name: 'RFC_ABAP_INSTALL_AND_RUN', parameters: { PROGRAM: lines.map(LINE => ({ LINE })) } });
const r = res.result || res;
writeFileSync(out, JSON.stringify({ err: r.ERRORMESSAGE || res.error || '', writes: (r.WRITES || []).map(w => w.ZEILE) }));
console.log('ERR:', r.ERRORMESSAGE || res.error || '-', 'LINES:', (r.WRITES || []).length);
